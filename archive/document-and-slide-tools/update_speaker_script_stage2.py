def set_text(paragraph, text):
    runs = paragraph.runs
    if runs:
        runs[0].text = text
        for run in runs[1:]:
            run._element.getparent().remove(run._element)
    else:
        paragraph.add_run(text)


def find_exact(text):
    matches = [p for p in doc.paragraphs if p.text == text]
    if len(matches) != 1:
        raise RuntimeError(f"expected one paragraph, found {len(matches)}: {text!r}")
    return matches[0]


def replace_exact(old, new):
    set_text(find_exact(old), new)


def elements_between(start_text, end_text):
    paragraphs = doc.paragraphs
    start = next(i for i, p in enumerate(paragraphs) if p.text == start_text)
    end = next(i for i, p in enumerate(paragraphs) if i > start and p.text == end_text)
    return [p._p for p in paragraphs[start:end]]


def paragraph_before(text):
    paragraphs = doc.paragraphs
    idx = next(i for i, p in enumerate(paragraphs) if p.text == text)
    return paragraphs[idx - 1]._p


def move_after(elements, anchor):
    for element in elements:
        anchor.addnext(element)
        anchor = element


