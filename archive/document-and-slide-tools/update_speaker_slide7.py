from pathlib import Path
from docx import Document


path = Path(r"D:\projects\car-detection-yolo\thesis\ارائه\متن_ارائه.docx")
tmp = path.with_name("متن_ارائه.tmp.docx")
doc = Document(path)


def replace(old, new):
    matches = [p for p in doc.paragraphs if p.text == old]
    if len(matches) != 1:
        raise RuntimeError(f"expected one paragraph, found {len(matches)}")
    p = matches[0]
    p.runs[0].text = new
    for run in p.runs[1:]:
        run._element.getparent().remove(run._element)


