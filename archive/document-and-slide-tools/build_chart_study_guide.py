def write(par,text,size=12,bold=False):
 text=DIACRITICS.sub('',str(text));pos=0
 for match in LATIN.finditer(text):
  if match.start()>pos:format_run(par.add_run(text[pos:match.start()]),size,bold)
  format_run(par.add_run(match.group()),size,bold,True);pos=match.end()
 if pos<len(text):format_run(par.add_run(text[pos:]),size,bold)

