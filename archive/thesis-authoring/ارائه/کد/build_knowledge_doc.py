def fa(n):
    """Persian digits, and the Persian thousands separator instead of a comma."""
    return str(n).translate(str.maketrans("0123456789,.", "۰۱۲۳۴۵۶۷۸۹٬٫"))


LATIN = re.compile(r"[A-Za-z][A-Za-z0-9_.@]*")


def _style(r, size, bold, color, latin_font, cs_font, rtl):
    r.bold = bold
    r.font.size = Pt(size)
    r.font.color.rgb = RGBColor.from_string(color)
    rPr = r._r.get_or_add_rPr()
    f = rPr.find(qn("w:rFonts"))
    if f is None:
        f = OxmlElement("w:rFonts")
        rPr.insert(0, f)
    f.set(qn("w:ascii"), latin_font)
    f.set(qn("w:hAnsi"), latin_font)
    f.set(qn("w:cs"), cs_font)
    sz = OxmlElement("w:szCs")
    sz.set(qn("w:val"), str(int(size * 2)))
    rPr.append(sz)
    if rtl:
        rPr.append(OxmlElement("w:rtl"))


def _run(par, text, size=13.5, bold=False, color=INK, mono=False):
    """Persian goes in right-to-left runs; Latin tokens get their own left-to-right
    run, otherwise Word redraws digits inside names like C3k2 as Persian ones."""
    if mono:
        r = par.add_run(text)
        _style(r, size, bold, color, "Consolas", "Consolas", False)
        return r
    pos = 0
    last = None
    for m in LATIN.finditer(text):
        if m.start() > pos:
            last = par.add_run(text[pos:m.start()])
            _style(last, size, bold, color, "Times New Roman", "B Zar", True)
        last = par.add_run(m.group())
        _style(last, size, bold, color, "Times New Roman", "Times New Roman", False)
        pos = m.end()
    if pos < len(text) or last is None:
        last = par.add_run(text[pos:])
        _style(last, size, bold, color, "Times New Roman", "B Zar", True)
    return last


def para(text, size=13.5, bold=False, color=INK, align=AL.JUSTIFY, indent=False,
         after=6, container=None, keep=False, before=0):
    p = (container or doc).add_paragraph()
    p.alignment = align
    p._p.get_or_add_pPr().append(OxmlElement("w:bidi"))
    pf = p.paragraph_format
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    pf.line_spacing = 1.35
    pf.keep_with_next = keep
    if indent:
        pf.first_line_indent = Cm(0.7)
    _run(p, text, size, bold, color)
    return p


def bullet(text, size=13.5, color=INK, after=4):
    p = doc.add_paragraph()
    p.alignment = AL.JUSTIFY
    p._p.get_or_add_pPr().append(OxmlElement("w:bidi"))
    pf = p.paragraph_format
    pf.space_after = Pt(after)
    pf.line_spacing = 1.3
    pf.right_indent = Cm(0.6)
    _run(p, "•  ", size, True, NAVY)
    _run(p, text, size, False, color)
    return p


def code(lines, note=None):
    """Left-to-right monospace block on a tinted background."""
    tbl = doc.add_table(rows=1, cols=1)
    tbl.style = "Table Grid"
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = tbl.rows[0].cells[0]
    shade(cell, "F4F6F8")
    cell.paragraphs[0]._p.getparent().remove(cell.paragraphs[0]._p)
    for ln in lines:
        p = cell.add_paragraph()
        p.alignment = AL.LEFT
        pf = p.paragraph_format
        pf.space_after = Pt(0)
        pf.line_spacing = 1.15
        _run(p, ln if ln else " ", 10.5, False, "23415C", mono=True)
    if note:
        para(note, 12, False, SLATE, AL.RIGHT, after=10)
    else:
        para("", after=6)


def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)


def rtl_table(tbl):
    tbl._tbl.tblPr.append(OxmlElement("w:bidiVisual"))


def table(rows, widths=None, size=12, head=True, mono_cols=()):
    tbl = doc.add_table(rows=len(rows), cols=len(rows[0]))
    tbl.style = "Table Grid"
    rtl_table(tbl)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = tbl.cell(i, j)
            if i == 0 and head:
                shade(cell, TINT)
            cell.paragraphs[0]._p.getparent().remove(cell.paragraphs[0]._p)
            p = cell.add_paragraph()
            p.alignment = AL.CENTER
            p._p.get_or_add_pPr().append(OxmlElement("w:bidi"))
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.15
            _run(p, str(val), size, i == 0 and head, NAVY if (i == 0 and head) else INK,
                 mono=(j in mono_cols and not (i == 0 and head)))
    if widths:
        for j, w in enumerate(widths):
            for row in tbl.rows:
                row.cells[j].width = Cm(w)
    para("", after=8)
    return tbl


def box(text, fill=TINT_G, color=GREEN, size=13):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.style = "Table Grid"
    cell = tbl.rows[0].cells[0]
    shade(cell, fill)
    cell.paragraphs[0]._p.getparent().remove(cell.paragraphs[0]._p)
    para(text, size, True, color, AL.JUSTIFY, after=0, container=cell)
    para("", after=8)


def heading(text, level):
    size = {1: 17, 2: 14.5, 3: 13.5}[level]
    p = para(text, size, True, NAVY, AL.RIGHT, after=6, keep=True,
             before={1: 20, 2: 12, 3: 8}[level])
    if level == 1:
        pPr = p._p.get_or_add_pPr()
        bdr = OxmlElement("w:pBdr")
        b = OxmlElement("w:bottom")
        b.set(qn("w:val"), "single")
        b.set(qn("w:sz"), "8")
        b.set(qn("w:color"), NAVY)
        b.set(qn("w:space"), "4")
        bdr.append(b)
        pPr.append(bdr)
    return p


